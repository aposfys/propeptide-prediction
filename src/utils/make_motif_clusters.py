'''
Reproduce DeepPeptide's partition-balancing label: k-means on peptide flank motifs.

The Methods specify it exactly, which means it can be reproduced rather than
replaced:

  "We based our clustering on the flanking motifs of the peptides, as these are
   presumably the main causal feature that gives rise to peptide cleavage. We
   extracted the two AAs before the N and after the C terminus of each peptide.
   To capture biochemical characteristics, we encoded each AA using ESM-2 and
   concatenated the resulting four embedding vectors. On the concatenated
   vectors, we performed k-means clustering. We found that a value of k = 50
   yields a useful number..."

That is what the `motif_cluster=13` field in the distributed FASTA headers is,
and what GraphPart balanced the five folds on. Without it a rebuilt dataset is
partitioned on a different principle from the original, and the reason the
original balanced at all -- "the labeled classes are highly heterogeneous and
unlikely to be generated by the same biological process" -- applies at least as
strongly to a wider window, which mixes convertase sites with zymogen prodomains.

WHAT THIS DOES DIFFERENTLY, and it is deliberate
The original clustered the flanks of PEPTIDES. This clusters the flanks of
PROPEPTIDES, because the rebuilt dataset is propeptide-only and peptide flanks
would balance the folds on a feature the model never predicts.

k-means is seeded (`--seed`), so the assignment is reproducible, but it will not
be identical to the original's cluster ids -- different inputs, different
centroids. The scheme is reproduced, not the exact clustering.

NO NEW EMBEDDING EXTRACTION. Per-residue ESM-2 embeddings already exist for the
benchmark; this reads the four flank vectors out of them.

Usage
-----
    python -m src.utils.make_motif_clusters \
        --data_file data_v2/labeled_sequences.csv \
        --embeddings_dir /mnt/storage/fysekidis/embeddings/esm2 \
        --fasta_in data_v2/protein_sequences.fasta \
        --fasta_out data_v2/protein_sequences_clustered.fasta
'''
import argparse
import collections
import json
import os
import re
from hashlib import md5

import numpy as np
import pandas as pd
import torch


def hash_aa_string(string: str) -> str:
    return md5(string.encode()).digest().hex()


def parse_coords(text):
    out = []
    for chunk in str(text).split(','):
        chunk = chunk.strip().strip('()')
        if '-' in chunk:
            a, b = chunk.split('-')
            out.append((int(a), int(b)))
    return out


def flank_vector(embedding, start, end):
    '''Concatenate the two residues before the N terminus and the two after the C.

    Positions are 1-based and inclusive, so the N flank is rows start-3 and
    start-2 and the C flank is rows end and end+1. Out-of-range flanks (a
    propeptide at the very start or end of a chain) are zero-filled rather than
    clamped: clamping would silently substitute a real residue's vector for a
    residue that does not exist.
    '''
    dim = embedding.shape[1]
    length = embedding.shape[0]
    parts = []
    for index in (start - 3, start - 2, end, end + 1):
        parts.append(embedding[index] if 0 <= index < length else torch.zeros(dim))
    return torch.cat(parts).numpy()


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--data_file', required=True)
    parser.add_argument('--embeddings_dir', required=True,
                        help='Per-residue ESM-2 embeddings, keyed by sequence md5.')
    parser.add_argument('--fasta_in', required=True)
    parser.add_argument('--fasta_out', required=True)
    parser.add_argument('--k', type=int, default=50,
                        help="DeepPeptide's value. They note it is not the "
                             'strictly optimal number, which is higher, but a '
                             'higher k yields singleton clusters that cannot be '
                             'used for partitioning.')
    parser.add_argument('--seed', type=int, default=42)
    args = parser.parse_args()

    from sklearn.cluster import KMeans

    frame = pd.read_csv(args.data_file).fillna('')
    vectors, owners = [], []
    missing = 0
    for _, row in frame.iterrows():
        spans = parse_coords(row['propeptide_coordinates'])
        if not spans:
            continue
        path = os.path.join(args.embeddings_dir,
                            f'{hash_aa_string(str(row["sequence"]))}.pt')
        if not os.path.isfile(path):
            missing += 1
            continue
        embedding = torch.load(path).to(torch.float32)
        for start, end in spans:
            vectors.append(flank_vector(embedding, start, end))
            owners.append(str(row['protein_id']))

    if not vectors:
        raise SystemExit('No flank vectors built. Check --embeddings_dir.')
    if missing:
        print(f'{missing} proteins had no embedding and were skipped')

    matrix = np.vstack(vectors)
    print(f'{matrix.shape[0]} propeptide flank motifs, {matrix.shape[1]} dims '
          f'(4 x {matrix.shape[1] // 4})')
    print(f'k-means, k={args.k}, seed={args.seed}...')
    labels = KMeans(n_clusters=args.k, random_state=args.seed,
                    n_init=10).fit_predict(matrix)

    # A protein with several propeptides gets several cluster ids. GraphPart
    # takes one label per sequence, so the most frequent is used, ties broken by
    # the lowest id so the result does not depend on dict ordering.
    per_protein = collections.defaultdict(list)
    for accession, label in zip(owners, labels):
        per_protein[accession].append(int(label))
    chosen = {}
    for accession, assigned in per_protein.items():
        counts = collections.Counter(assigned)
        best = max(counts.values())
        chosen[accession] = min(k for k, v in counts.items() if v == best)

    header = re.compile(r'^>(\S+?)\|')
    written = 0
    with open(args.fasta_in) as source, open(args.fasta_out, 'w') as target:
        for line in source:
            if line.startswith('>'):
                match = header.match(line)
                accession = match.group(1) if match else line[1:].split()[0]
                base = line.rstrip('\n').split('|mechanism=')[0]
                cluster = chosen.get(accession, -1)
                target.write(f'{base}|motif_cluster={cluster}\n')
                written += 1
            else:
                target.write(line)

    json.dump({'k': args.k, 'seed': args.seed, 'n_motifs': int(matrix.shape[0]),
               'n_proteins_labelled': len(chosen),
               'cluster_sizes': dict(collections.Counter(chosen.values()))},
              open(args.fasta_out + '.clusters.json', 'w'), indent=2)

    sizes = collections.Counter(chosen.values())
    print(f'{written} FASTA records written to {args.fasta_out}')
    print(f'cluster sizes: min {min(sizes.values())}, max {max(sizes.values())}, '
          f'{len(sizes)} non-empty of {args.k}')
    print(f'{sum(1 for v in chosen.values() if v == -1)} proteins unlabelled '
          '(negatives keep motif_cluster=-1)')
    print('\nPartition with the published settings:')
    print(f'  graphpart needle -ff {args.fasta_out} \\')
    print('      -th 0.3 -pa 5 -ln motif_cluster --no-moving \\')
    print('      -on graphpart_assignments.csv')
    print('\n  --no-moving is in the paper: "To keep fold sizes similar, we '
          'executed\n  the tool using the --no-moving flag, as indicated in the '
          'documentation."')


if __name__ == '__main__':
    main()
